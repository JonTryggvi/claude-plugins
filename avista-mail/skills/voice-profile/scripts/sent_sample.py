#!/usr/bin/env python3
"""Pull a sample of the user's own SENT Gmail messages for voice analysis. Read-only.

Reuses the OAuth setup of ../../gmail-draft/scripts/gmail_draft.py (same
~/.claude/.env keys, same self-healing sign-in). Needs only gmail.readonly,
which that setup already grants. Nothing is sent, labelled, modified or uploaded.

What it does:
  1. Lists the newest POOL message ids carrying the SENT label (1 request per
     500) and picks N of them spread evenly across the pool, so the sample
     covers weeks or months rather than the last few days.
  2. Fetches them with the Gmail batch endpoint, 25 messages per HTTP request,
     paced to ~940 quota units a minute; rate-limited messages are retried
     after a back-off. 200 messages take about a minute.
  3. Keeps only the text the user typed: drops quoted replies, forwarded
     blocks, the Gmail signature and "Sent from my iPhone" lines.
  4. Writes samples.txt and summary.json into a fresh private temp directory
     (mode 700) and prints the directory and a summary. Bodies are never
     printed to stdout. Recipient addresses are not stored, only whether a
     message went inside the user's own domain or outside it.

Commands:
  fetch [--count N] [--pool P] [--out-parent DIR] [--plan-only]
  clean DIR        delete a sample directory this script created (and nothing else)

Delete the directory with `clean` as soon as the profile is written.
"""
import argparse
import base64
import importlib.util
import json
import math
import re
import shutil
import statistics
import sys
import tempfile
import time
import urllib.error
import urllib.request
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

GMAIL_DRAFT = Path(__file__).resolve().parents[2] / 'gmail-draft' / 'scripts' / 'gmail_draft.py'
BATCH_URL = 'https://gmail.googleapis.com/batch/gmail/v1'
API = 'https://gmail.googleapis.com/gmail/v1/users/me'
LIST_PAGE = 500          # messages.list maximum page size
BATCH_SIZE = 25          # inner requests run concurrently; 50 trips Gmail's per-user concurrency limit (403)
BATCH_PAUSE = 8.0        # 25 x 5 units every 8 s = ~940 units/min. Some projects set the per-minute
                         # per-user cap far below Google's public default (seen 2026-11-11), so pace low.
BACKOFF = [20, 40, 70]   # seconds to wait after a rate-limit reply before retrying
MARKER = '.voice-sample'
MAX_BODY_CHARS = 3000

QUOTE_HEADERS = [
  # "On <date>, <name> wrote:" / "Þann <date> skrifaði <name>:" in several languages; may wrap
  # over a line or two, never across a blank line, and the first line carries a digit (date/time)
  re.compile(r'^(On|Þann|Den|Am|Le|El|Op|Il) (?=[^\n]*\d)(?:(?!\n\s*\n)[\s\S]){0,300}?'
             r'(wrote|skrifaði|skrev|schrieb|a écrit|escribió|schreef|ha scritto)'
             r'(?:(?!\n\s*\n)[\s\S]){0,200}?:\s*$', re.M),
  re.compile(r'^-{2,}\s*(Original Message|Upprunaleg skilaboð|Forwarded message|Áframsend skilaboð)', re.M | re.I),
  re.compile(r'^_{10,}\s*$', re.M),  # Outlook separator line
  re.compile(r'^\*?(From|Frá|Fra|Von|De)\s*:\*?\s.+\n\*?(Sent|Sent:|Date|Dagsetning|Datum|Envoyé)', re.M),
]
SIG_LINES = re.compile(r'^-- ?$|Sent from my \w+|Sent from Outlook|^Sent úr .*$|^Sent með .*$|Get Outlook for ', re.M)
AUTOMATED = re.compile(r'automatically generated by Gmail|Apple Mail sent this email to unsubscribe|'
                       r'^Your sign-in code is|^Your verification code', re.I | re.M)
CONTACT_LINE = re.compile(r'www\.|https?://|[\w.+-]+@[\w-]+\.\w|￼|^\s*(kt\.|tel|sími|s\.|mobile|gsm)\b'
                          r'|^\s*[A-Z]{0,3}\s*\+?\d[\d ()\-]{6,}\s*$|\+\d{2,3}[\s\d\-]{6,}', re.I)
CALENDAR = re.compile(r'^(Accepted|Declined|Tentatively accepted|Invitation|Updated invitation|'
                      r'Samþykkt|Hafnað|Boð|Uppfært boð)\b', re.I)
IS_CHARS = re.compile(r'[ðþæÐÞÆ]')
IS_WORDS = {'og', 'að', 'er', 'ég', 'við', 'það', 'þetta', 'ekki', 'sem', 'á', 'í', 'fyrir', 'en', 'kveðja'}
EN_WORDS = {'the', 'and', 'is', 'to', 'you', 'i', 'it', 'for', 'we', 'that', 'this', 'thanks', 'best'}
ES_WORDS = {'el', 'la', 'los', 'las', 'de', 'que', 'y', 'por', 'para', 'con', 'una', 'gracias', 'saludo', 'estimado'}


def load_gmail_draft():
  if not GMAIL_DRAFT.exists():
    sys.exit(f'gmail_draft.py not found at {GMAIL_DRAFT}. The avista-mail plugin looks incomplete.')
  spec = importlib.util.spec_from_file_location('gmail_draft', GMAIL_DRAFT)
  module = importlib.util.module_from_spec(spec)
  spec.loader.exec_module(module)
  return module


# ---------- planning ----------

def plan(count: int, pool: int) -> dict:
  lists = math.ceil(pool / LIST_PAGE)
  batches = math.ceil(count / BATCH_SIZE)
  return {
    'messages': count,
    'pool': pool,
    'http_requests': 1 + 1 + lists + batches,  # token refresh, sendAs, list pages, batches
    'breakdown': {'token_refresh': 1, 'settings.sendAs': 1, 'messages.list': lists,
                  'batch_requests': batches, 'messages.get_inside_batches': count},
    'quota_units': 1 + 5 * lists + 5 * count,
    'est_seconds': round(batches * BATCH_PAUSE),
    'note': 'Gmail API has no per-call charge, only per-user rate quotas. Batches are paced and retried on rate limits.',
  }


# ---------- fetching ----------

def get_json(path: str, token: str) -> dict:
  """GET with back-off on rate-limit replies (429, or 403 rateLimitExceeded)."""
  for wait in BACKOFF + [None]:
    req = urllib.request.Request(API + path, headers={'Authorization': f'Bearer {token}'})
    try:
      with urllib.request.urlopen(req) as resp:
        return json.load(resp)
    except urllib.error.HTTPError as err:
      body = err.read().decode(errors='replace')
      limited = err.code == 429 or (err.code == 403 and 'ateLimit' in body)
      if not limited or wait is None:
        sys.exit(f'Gmail API GET {path} -> {err.code}: {body[:400]}')
      print(f'rate-limited on {path.split("?")[0]}, waiting {wait}s', file=sys.stderr)
      time.sleep(wait)

def list_sent_ids(token: str, count: int) -> list:
  ids, page = [], None
  while len(ids) < count:
    size = min(LIST_PAGE, count - len(ids))
    path = f'/messages?labelIds=SENT&maxResults={size}' + (f'&pageToken={page}' if page else '')
    resp = get_json(path, token)
    ids += [m['id'] for m in resp.get('messages', [])]
    page = resp.get('nextPageToken')
    if not page:
      break
  return ids[:count]


def batch_get(token: str, ids: list) -> tuple:
  """One HTTP request carrying len(ids) messages.get calls. Returns (messages, ids_to_retry)."""
  boundary = 'voice_sample_batch'
  parts = []
  for i, mid in enumerate(ids):
    parts.append(f'--{boundary}\r\nContent-Type: application/http\r\nContent-ID: <item{i}>\r\n\r\n'
                 f'GET /gmail/v1/users/me/messages/{mid}?format=full\r\n\r\n')
  body = (''.join(parts) + f'--{boundary}--\r\n').encode()
  req = urllib.request.Request(BATCH_URL, data=body, method='POST', headers={
    'Authorization': f'Bearer {token}', 'Content-Type': f'multipart/mixed; boundary={boundary}',
  })
  try:
    with urllib.request.urlopen(req) as resp:
      ctype = resp.headers.get('Content-Type', '')
      raw = resp.read().decode('utf-8', errors='replace')
  except urllib.error.HTTPError as err:
    sys.exit(f'Gmail batch request -> {err.code}: {err.read().decode(errors="replace")[:400]}')

  match = re.search(r'boundary=("?)([^";]+)\1', ctype)
  if not match:
    sys.exit('Gmail batch response had no multipart boundary.')
  messages, retry = [], []
  for part in raw.split('--' + match.group(2)):
    status = re.search(r'HTTP/1\.1 (\d{3})', part)
    item = re.search(r'Content-ID: <response-item(\d+)>', part)
    if not status or not item:
      continue
    code, idx = int(status.group(1)), int(item.group(1))
    if code == 200:
      start = part.find('{', status.end())
      messages.append(json.loads(part[start:part.rfind('}') + 1]))
    elif code in (429, 500, 503) or (code == 403 and re.search(r'(?i)rate ?limit|concurrent', part)):
      retry.append(ids[idx])
    else:
      reason = re.search(r'"message":\s*"([^"]{0,160})', part)
      print(f'skipped one message: HTTP {code} {reason.group(1) if reason else ""}', file=sys.stderr)
  return messages, retry


def fetch_all(token: str, ids: list) -> list:
  messages, queue, rounds = [], list(ids), 0
  while queue and rounds <= len(BACKOFF):
    retry = []
    for start in range(0, len(queue), BATCH_SIZE):
      got, again = batch_get(token, queue[start:start + BATCH_SIZE])
      messages += got
      retry += again
      time.sleep(BATCH_PAUSE)
    queue, rounds = retry, rounds + 1
    if queue and rounds <= len(BACKOFF):
      wait = BACKOFF[rounds - 1]
      print(f'rate-limited on {len(queue)} messages, retrying in {wait}s', file=sys.stderr)
      time.sleep(wait)
  if queue:
    print(f'gave up on {len(queue)} rate-limited messages', file=sys.stderr)
  return messages


# ---------- text extraction ----------

def b64(data: str) -> bytes:
  return base64.urlsafe_b64decode(data + '=' * (-len(data) % 4))


def part_text(part: dict) -> tuple:
  """Return (plain, html) text found in a payload tree."""
  mime = part.get('mimeType', '')
  if part.get('filename'):
    return '', ''
  data = part.get('body', {}).get('data')
  if data and mime in ('text/plain', 'text/html'):
    charset = 'utf-8'
    for h in part.get('headers', []):
      if h['name'].lower() == 'content-type':
        found = re.search(r'charset="?([\w-]+)', h['value'], re.I)
        charset = found.group(1) if found else charset
    try:
      text = b64(data).decode(charset, errors='replace')
    except LookupError:
      text = b64(data).decode('utf-8', errors='replace')
    return (text, '') if mime == 'text/plain' else ('', text)
  plain, markup = '', ''
  for sub in part.get('parts', []):
    p, h = part_text(sub)
    plain, markup = plain or p, markup or h
  return plain, markup


def html_to_plain(markup: str) -> str:
  import html as htmllib
  markup = re.sub(r'(?is)<(style|script|head)\b.*?</\1>', '', markup)
  markup = re.sub(r'(?is)<div class="gmail_quote.*', '', markup)
  markup = re.sub(r'(?is)<blockquote\b.*?</blockquote>', '', markup)
  markup = re.sub(r'(?i)<br\s*/?>|</div>|</p>|</li>', '\n', markup)
  return htmllib.unescape(re.sub(r'<[^>]+>', '', markup))


def strip_reply(text: str, signature_lines: list) -> str:
  text = text.replace('\r\n', '\n').replace('\u00a0', ' ')
  cut = len(text)
  for pattern in QUOTE_HEADERS:
    found = pattern.search(text)
    if found:
      cut = min(cut, found.start())
  text = text[:cut]
  text = '\n'.join(l for l in text.split('\n') if not l.lstrip().startswith('>'))
  found = SIG_LINES.search(text)
  if found:
    text = text[:found.start()]
  lowered = text.lower()
  for line in signature_lines:  # the Gmail signature block, when pasted without a "-- " marker
    pos = lowered.find(line.lower())
    if pos > 0:
      text, lowered = text[:pos], lowered[:pos]
  # older or mobile signatures differ from the current one: drop trailing contact lines
  lines = text.rstrip().split('\n')
  while lines and (not lines[-1].strip() or CONTACT_LINE.search(lines[-1])):
    lines.pop()
  text = '\n'.join(lines)
  text = re.sub(r'[ \t]+\n', '\n', text)
  return re.sub(r'\n{3,}', '\n\n', text).strip()


def guess_lang(text: str) -> str:
  words = re.findall(r"[a-záéíóúýñðþæö']+", text.lower())
  scores = {
    'is': sum(w in IS_WORDS for w in words) + 2 * len(IS_CHARS.findall(text)),
    'en': sum(w in EN_WORDS for w in words),
    'es': sum(w in ES_WORDS for w in words) + 2 * len(re.findall(r'[ñ¿¡]', text)),
  }
  best = max(scores, key=scores.get)
  return best if scores[best] else 'other'


def headers_of(msg: dict) -> dict:
  return {h['name'].lower(): h['value'] for h in msg.get('payload', {}).get('headers', [])}


def audience(hdrs: dict, own_domains: set) -> str:
  rcpts = ','.join(hdrs.get(k, '') for k in ('to', 'cc'))
  domains = {d.lower() for d in re.findall(r'@([\w.-]+)', rcpts)}
  if not domains:
    return 'unknown'
  if domains <= own_domains:
    return 'internal'
  return 'mixed' if domains & own_domains else 'external'


def to_sample(msg: dict, own_addresses: set, own_domains: set, signature_lines: list):
  hdrs = headers_of(msg)
  sender = re.findall(r'[\w.+-]+@[\w.-]+', hdrs.get('from', '').lower())
  if own_addresses and sender and sender[0] not in own_addresses:
    return None  # sent by a delegate or an app on the user's behalf
  subject = hdrs.get('subject', '')
  if CALENDAR.match(subject) or 'CHAT' in msg.get('labelIds', []):
    return None
  plain, markup = part_text(msg.get('payload', {}))
  body = strip_reply(plain or html_to_plain(markup), signature_lines)
  if not body or AUTOMATED.search(body):
    return None
  kind = 'forward' if re.match(r'(?i)(fwd?|fw|áfr)\s*:', subject) else 'reply' if hdrs.get('in-reply-to') else 'new'
  date = datetime.fromtimestamp(int(msg.get('internalDate', '0')) / 1000, tz=timezone.utc)
  return {
    'date': date.strftime('%Y-%m-%d'),
    'subject': subject,
    'kind': kind,
    'audience': audience(hdrs, own_domains),
    'lang': guess_lang(body),
    'words': len(body.split()),
    'body': body[:MAX_BODY_CHARS],
  }


# ---------- output ----------

def summarise(samples: list, fetched: int) -> dict:
  def firsts(s):
    return s['body'].split('\n', 1)[0].strip()[:60]

  def lasts(s):
    lines = [l.strip() for l in s['body'].split('\n') if l.strip()]
    return ' / '.join(lines[-2:])[:60] if len(lines) > 1 else ''

  by_lang = {}
  for lang in sorted({s['lang'] for s in samples}):
    group = [s for s in samples if s['lang'] == lang]
    words = [s['words'] for s in group]
    by_lang[lang] = {
      'messages': len(group),
      'median_words': statistics.median(words),
      'p90_words': sorted(words)[int(0.9 * (len(words) - 1))],
      'under_25_words': sum(1 for s in group if s['words'] < 25),
    }
  return {
    'fetched': fetched,
    'kept': len(samples),
    'date_range': [min(s['date'] for s in samples), max(s['date'] for s in samples)] if samples else [],
    'by_lang': by_lang,
    'by_kind': dict(Counter(s['kind'] for s in samples)),
    'by_audience': dict(Counter(s['audience'] for s in samples)),
    'common_first_lines': [[k, v] for k, v in Counter(map(firsts, samples)).most_common(25) if v > 1],
    'common_last_two_lines': [[k, v] for k, v in Counter(filter(None, map(lasts, samples))).most_common(25) if v > 1],
  }


def write_out(samples: list, summary: dict, parent) -> Path:
  out = Path(tempfile.mkdtemp(prefix='voice-sample-', dir=parent))  # mkdtemp creates it mode 700
  (out / MARKER).write_text('created by sent_sample.py; delete with: sent_sample.py clean <dir>\n')
  with open(out / 'samples.txt', 'w', encoding='utf-8') as fh:
    for i, s in enumerate(samples, 1):
      fh.write(f"=== #{i} | {s['date']} | {s['lang']} | {s['kind']} | {s['audience']} | {s['words']} words\n")
      fh.write(f"Subject: {s['subject']}\n\n{s['body']}\n\n")
  (out / 'summary.json').write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding='utf-8')
  for f in out.iterdir():
    f.chmod(0o600)
  return out


# ---------- commands ----------

def cmd_fetch(args) -> None:
  count = max(1, min(args.count, 500))
  pool = max(count, min(args.pool, 2000))
  print(json.dumps({'plan': plan(count, pool)}, indent=2), file=sys.stderr)
  if args.plan_only:
    return
  gd = load_gmail_draft()
  token = gd.access_token()

  aliases = get_json('/settings/sendAs', token).get('sendAs', [])
  own_addresses = {a['sendAsEmail'].lower() for a in aliases if a.get('sendAsEmail')}
  own_domains = {a.split('@', 1)[1] for a in own_addresses}
  signature_lines = []
  for alias in aliases:
    sig = gd.html_to_text(alias.get('signature', '') or '').replace('\u00a0', ' ')
    first = next((l.strip() for l in sig.split('\n') if len(l.strip()) > 3), '')
    if first:
      signature_lines.append(first)

  pool_ids = list_sent_ids(token, pool)
  step = len(pool_ids) / count
  ids = [pool_ids[int(i * step)] for i in range(min(count, len(pool_ids)))]
  messages = fetch_all(token, ids)
  samples = [s for s in (to_sample(m, own_addresses, own_domains, signature_lines) for m in messages) if s]
  samples.sort(key=lambda s: s['date'], reverse=True)
  summary = summarise(samples, len(messages))
  out = write_out(samples, summary, args.out_parent)
  print(json.dumps({
    'sample_dir': str(out),
    'files': ['samples.txt', 'summary.json'],
    'fetched': len(messages),
    'kept': len(samples),
    'by_lang': {k: v['messages'] for k, v in summary['by_lang'].items()},
    'date_range': summary['date_range'],
  }, indent=2))


def cmd_clean(args) -> None:
  target = Path(args.dir).resolve()
  if not (target / MARKER).is_file() or not target.name.startswith('voice-sample-'):
    sys.exit(f'{target} is not a sample directory made by this script; not deleting it.')
  shutil.rmtree(target)
  print(json.dumps({'deleted': str(target)}))


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  sub = parser.add_subparsers(dest='cmd', required=True)
  p_fetch = sub.add_parser('fetch')
  p_fetch.add_argument('--count', type=int, default=200, help='sent messages to sample (default 200, max 500)')
  p_fetch.add_argument('--pool', type=int, default=1000,
                       help='spread the sample evenly over the newest P sent messages (default 1000, max 2000)')
  p_fetch.add_argument('--out-parent', help='directory to create the private sample dir in (default: system temp)')
  p_fetch.add_argument('--plan-only', action='store_true', help='print the request count and exit without calling Gmail')
  p_fetch.set_defaults(func=cmd_fetch)
  p_clean = sub.add_parser('clean')
  p_clean.add_argument('dir')
  p_clean.set_defaults(func=cmd_clean)
  args = parser.parse_args()
  args.func(args)


if __name__ == '__main__':
  main()
